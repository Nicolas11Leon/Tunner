import 'package:flutter/material.dart';
import '../../../core/design_system/studio_design_system.dart';
import '../../acoustic_lab/presentation/harmonic_spectrogram_modal.dart';
import '../../chord_analyzer/presentation/chord_analyzer_modal.dart';
import '../../drone/presentation/harmonic_drone_modal.dart';
import '../../ear_training/presentation/blind_ear_trainer_modal.dart';
import '../../song_library/presentation/studio_assets_modals.dart';
import '../../tuner_viewmodel.dart';
import '../../workspaces/presentation/polyphonic_synth_modal.dart';
import 'keyboard_shortcuts_modal.dart';

/// Constructor modular de sugerencias de comandos y módulos para la barra de comandos de Tunner Studio.
class StudioPromptSuggestionsBuilder {
  const StudioPromptSuggestionsBuilder._();

  static List<PromptSuggestion> build({
    required BuildContext context,
    required TunerViewModel viewModel,
    required void Function(int tabIndex) onNavigateTab,
    required void Function(String rawInput) onParseAndSetBpm,
    required void Function(String rawInput) onParseAndSetPitch,
    required VoidCallback onToggleTerminal,
    required VoidCallback onOpenMasterConsole,
    required VoidCallback onOpenInstrumentSelector,
    required VoidCallback onMasterTogglePlayPause,
    required VoidCallback onMasterStop,
  }) {
      return [
        PromptSuggestion(
          id: 'cmd_tuner',
          trigger: '/',
          command: '/afinar',
          title: 'Afinador Estroboscópico de Precisión',
          description: 'Afinación en tiempo real con aguja centesimal ±0.1c',
          category: 'Afinación',
          shortcut: 'A',
          icon: Icons.tune_rounded,
          onExecute: (_) => onNavigateTab(1),
        ),
        PromptSuggestion(
          id: 'cmd_metro',
          trigger: '/',
          command: '/metro',
          title: viewModel.isMetronomeActive ? 'Pausar Metrónomo' : 'Iniciar Metrónomo Continuo',
          description: 'Alternar pulso rítmico acústico a ${viewModel.bpm.round()} BPM',
          category: 'Transporte',
          shortcut: 'Espacio',
          icon: Icons.access_time_rounded,
          onExecute: (_) => viewModel.toggleMetronome(),
        ),
        PromptSuggestion(
          id: 'cmd_bpm',
          trigger: '/',
          command: '/bpm',
          title: 'Ajustar Tempo (BPM)',
          description: 'Establecer tempo del metrónomo (ej. /bpm 120)',
          category: 'Metrónomo',
          shortcut: '[ / ]',
          icon: Icons.speed_rounded,
          onExecute: (raw) => onParseAndSetBpm(raw),
        ),
        PromptSuggestion(
          id: 'cmd_calibrar',
          trigger: '/',
          command: '/calibrar',
          title: 'Calibrar Tono A4 (Hz)',
          description: 'Calibrar frecuencia de referencia (ej. /calibrar 442)',
          category: 'Afinación',
          shortcut: 'Alt+↑',
          icon: Icons.waves_rounded,
          onExecute: (raw) => onParseAndSetPitch(raw),
        ),
        PromptSuggestion(
          id: 'cmd_record',
          trigger: '/',
          command: '/grabar',
          title: viewModel.isRecording ? 'Detener Grabación WAV' : 'Grabar Toma de Práctica',
          description: 'Capturar audio en vivo para autoevaluación',
          category: 'Grabación',
          shortcut: 'R',
          icon: Icons.fiber_manual_record_rounded,
          onExecute: (_) {
            if (viewModel.isRecording) {
              viewModel.stopPracticeRecording();
            } else {
              viewModel.startPracticeRecording();
            }
          },
        ),
        PromptSuggestion(
          id: 'cmd_spectrogram',
          trigger: '/',
          command: '/espectrograma',
          title: 'Espectrograma FFT en Vivo',
          description: 'Distribución armónica y densidad espectral',
          category: 'Laboratorio',
          icon: Icons.analytics_outlined,
          onExecute: (_) => HarmonicSpectrogramModal.show(context),
        ),
        PromptSuggestion(
          id: 'cmd_drone',
          trigger: '/',
          command: '/dron',
          title: 'Dron Armónico & Temperamentos',
          description: 'Tono sinusoidal continuo para práctica pura',
          category: 'Afinación',
          icon: Icons.volume_up_outlined,
          onExecute: (_) => HarmonicDroneModal.show(context, viewModel),
        ),
        PromptSuggestion(
          id: 'cmd_chords',
          trigger: '/',
          command: '/acordes',
          title: 'Analizador Polifónico de Acordes',
          description: 'Detección simultánea de tríadas y extensiones',
          category: 'Laboratorio',
          shortcut: 'Shift+C',
          icon: Icons.stacked_bar_chart_rounded,
          onExecute: (_) => ChordAnalyzerModal.show(context, viewModel),
        ),
        PromptSuggestion(
          id: 'cmd_ear',
          trigger: '/',
          command: '/oido',
          title: 'Entrenador Auditivo a Ciegas',
          description: 'Discriminación de intervalos armónicos',
          category: 'Conservatorio',
          shortcut: 'Shift+E',
          icon: Icons.hearing_outlined,
          onExecute: (_) => BlindEarTrainerModal.show(context, viewModel),
        ),
        PromptSuggestion(
          id: 'cmd_rack',
          trigger: '/',
          command: '/rack',
          title: 'Rack Modular de Pedales DSP',
          description: 'Estudio de efectos encadenados en tiempo real',
          category: 'Estudio',
          shortcut: '4',
          icon: Icons.view_agenda_outlined,
          onExecute: (_) => onNavigateTab(3),
        ),
        PromptSuggestion(
          id: 'cmd_scores',
          trigger: '/',
          command: '/partituras',
          title: 'Biblioteca & Notación MusicXML',
          description: 'Lector, visor interactivo y stems de obras',
          category: 'Composición',
          shortcut: '5',
          icon: Icons.menu_book_outlined,
          onExecute: (_) => onNavigateTab(4),
        ),
        PromptSuggestion(
          id: 'cmd_instrument',
          trigger: '/',
          command: '/instrumento',
          title: 'Seleccionar Instrumento Musical',
          description: 'Cambiar familia, clave y transposición',
          category: 'Configuración',
          shortcut: 'Ctrl+I',
          icon: Icons.music_note_rounded,
          onExecute: (_) => onOpenInstrumentSelector(),
        ),
        PromptSuggestion(
          id: 'cmd_mute',
          trigger: '/',
          command: '/mute',
          title: 'Silencio de Pánico (Panic Mute)',
          description: 'Detener metrónomo y grabación de inmediato',
          category: 'Transporte',
          shortcut: '0',
          icon: Icons.volume_off_rounded,
          onExecute: (_) {
            if (viewModel.isMetronomeActive) viewModel.toggleMetronome();
            if (viewModel.isRecording) viewModel.stopPracticeRecording();
          },
        ),
        PromptSuggestion(
          id: 'cmd_master',
          trigger: '/',
          command: '/master',
          title: 'Consola Maestra de E/S de Hardware',
          description: 'Matriz de ruteo, vúmetro y masterización DSP',
          category: 'Hardware',
          shortcut: 'Ctrl+Shift+I',
          icon: Icons.tune_rounded,
          onExecute: (_) => onOpenMasterConsole(),
        ),
        PromptSuggestion(
          id: 'cmd_playall',
          trigger: '/',
          command: '/playall',
          title: 'Transporte Global: Reproducir Todo',
          description: 'Sincronizar metrónomo, consola DJ y partituras',
          category: 'Transporte',
          shortcut: 'Shift+Espacio',
          icon: Icons.play_arrow_rounded,
          onExecute: (_) => onMasterTogglePlayPause(),
        ),
        PromptSuggestion(
          id: 'cmd_stopall',
          trigger: '/',
          command: '/stopall',
          title: 'Transporte Global: Detener Todo',
          description: 'Detener y reiniciar todos los generadores del estudio',
          category: 'Transporte',
          shortcut: 'Shift+Esc',
          icon: Icons.stop_rounded,
          onExecute: (_) => onMasterStop(),
        ),
        PromptSuggestion(
          id: 'cmd_synth',
          trigger: '/',
          command: '/synth',
          title: 'Sintetizador Polifónico SMuFL',
          description: 'Configurar osciladores, envolvente ADSR y timbres acústicos',
          category: 'Composición',
          shortcut: 'Ctrl+Shift+S',
          icon: Icons.piano,
          onExecute: (_) => PolyphonicSynthModal.show(context, viewModel, viewModel.currentPalette),
        ),
        PromptSuggestion(
          id: 'cmd_score_play',
          trigger: '/',
          command: '/score',
          title: 'Partitura Interactiva: Reproducir Obra',
          description: 'Alternar lectura métrica y síntesis de la obra actual',
          category: 'Composición',
          shortcut: 'Espacio',
          icon: Icons.music_note,
          onExecute: (_) {
            if (viewModel.isMetronomePlaying) {
              viewModel.stopSong();
            } else {
              viewModel.startSongWithCountIn();
            }
          },
        ),
        PromptSuggestion(
          id: 'cmd_project_export',
          trigger: '/',
          command: '/project',
          title: 'Proyecto: Exportar Paquete Canónico .tunner',
          description: 'Empaquetar sesión, partitura, presets y matriz con firma SHA-256',
          category: 'Proyectos',
          shortcut: 'Ctrl+S',
          icon: Icons.inventory_2,
          onExecute: (_) {
            final bytes = viewModel.exportCurrentProjectToTunner();
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(
                content: Text('Proyecto exportado a formato canónico .tunner (${bytes.lengthInBytes} bytes)'),
                backgroundColor: const Color(0xFF10B981),
                duration: const Duration(seconds: 3),
              ),
            );
          },
        ),
        PromptSuggestion(
          id: 'cmd_import',
          trigger: '/',
          command: '/importar',
          title: 'Importar Archivo Universal',
          description: 'Importar archivos MusicXML, MIDI, ABC, PDF o WAV',
          category: 'Archivos',
          shortcut: 'Ctrl+O',
          icon: Icons.file_open_outlined,
          onExecute: (_) => StudioAssetsModals.showImportScoreDialog(
            context: context,
            viewModel: viewModel,
            onNavigateToTab: onNavigateTab,
          ),
        ),
        PromptSuggestion(
          id: 'cmd_nueva_partitura',
          trigger: '/',
          command: '/nueva',
          title: 'Crear Nueva Partitura',
          description: 'Inicializar partitura en blanco en el espacio de trabajo',
          category: 'Composición',
          shortcut: 'Ctrl+N',
          icon: Icons.post_add_rounded,
          onExecute: (_) => StudioAssetsModals.showNewScoreDialog(
            context: context,
            viewModel: viewModel,
            onNavigateToTab: onNavigateTab,
          ),
        ),
        PromptSuggestion(
          id: 'cmd_save_preset',
          trigger: '/',
          command: '/preset',
          title: 'Guardar Preset de Afinación',
          description: 'Almacenar afinación actual en biblioteca local',
          category: 'Afinación',
          icon: Icons.bookmark_add_outlined,
          onExecute: (_) => StudioAssetsModals.showNewTuningPresetDialog(
            context: context,
            viewModel: viewModel,
          ),
        ),
        PromptSuggestion(
          id: 'cmd_dj',
          trigger: '/',
          command: '/dj',
          title: 'Consola DJ Pro Workstation',
          description: 'Mezclador de 2 Decks, jog scratch, stems isolator y sampler',
          category: 'Producción',
          shortcut: 'Alt+6',
          icon: Icons.album_rounded,
          onExecute: (_) => onNavigateTab(5),
        ),
        PromptSuggestion(
          id: 'cmd_consola',
          trigger: '/',
          command: '/consola',
          title: 'Consola DJ & Mezclador en Vivo',
          description: 'Abrir mesa de mezclas para directo y performance',
          category: 'Producción',
          icon: Icons.album_rounded,
          onExecute: (_) => onNavigateTab(5),
        ),
        PromptSuggestion(
          id: 'cmd_help',
          trigger: '/',
          command: '/help',
          title: 'Ayuda Universal & Matriz de Comandos',
          description: 'Catálogo exhaustivo de comandos y atajos de memoria muscular',
          category: 'Sistema',
          shortcut: '?',
          icon: Icons.help_outline_rounded,
          onExecute: (_) => KeyboardShortcutsCheatSheetModal.show(context: context, palette: viewModel.currentPalette),
        ),

        // Accesos a Módulos con @
        PromptSuggestion(
          id: 'mod_tuner',
          trigger: '@',
          command: '@afinador',
          title: 'Espacio de Afinación Orquestal',
          description: 'Navegar al afinador estroboscópico',
          category: 'Módulos',
          shortcut: 'Alt+1',
          icon: Icons.tune_rounded,
          onExecute: (_) => onNavigateTab(1),
        ),
        PromptSuggestion(
          id: 'mod_metronome',
          trigger: '@',
          command: '@metronomo',
          title: 'Metrónomo Determinista',
          description: 'Navegar al panel de control de tempo y pulso',
          category: 'Módulos',
          shortcut: 'Alt+0',
          icon: Icons.access_time_rounded,
          onExecute: (_) => onNavigateTab(0),
        ),
        PromptSuggestion(
          id: 'mod_studio',
          trigger: '@',
          command: '@rack',
          title: 'Espacio de Producción & Rack Modular',
          description: 'Navegar a la consola modular de efectos',
          category: 'Módulos',
          shortcut: 'Alt+4',
          icon: Icons.view_agenda_outlined,
          onExecute: (_) => onNavigateTab(3),
        ),
        PromptSuggestion(
          id: 'mod_conservatory',
          trigger: '@',
          command: '@conservatorio',
          title: 'Espacio de Aprendizaje & Pedagogía',
          description: 'Navegar al tutor guiado de compás y entonación',
          category: 'Módulos',
          shortcut: 'Alt+3',
          icon: Icons.school_outlined,
          onExecute: (_) => onNavigateTab(2),
        ),
        PromptSuggestion(
          id: 'mod_scores',
          trigger: '@',
          command: '@partituras',
          title: 'Espacio de Biblioteca & Partituras',
          description: 'Navegar al visor de notación musical',
          category: 'Módulos',
          shortcut: 'Alt+5',
          icon: Icons.menu_book_outlined,
          onExecute: (_) => onNavigateTab(4),
        ),
        PromptSuggestion(
          id: 'mod_dj',
          trigger: '@',
          command: '@dj',
          title: 'Consola DJ Pro Workstation',
          description: 'Navegar al espacio de DJ y mezcla 2-Decks',
          category: 'Módulos',
          shortcut: 'Alt+6',
          icon: Icons.album_rounded,
          onExecute: (_) => onNavigateTab(5),
        ),
        PromptSuggestion(
          id: 'mod_acoustics',
          trigger: '@',
          command: '@laboratorio',
          title: 'Espacio de Laboratorio Acústico',
          description: 'Abrir espectrograma FFT armónico',
          category: 'Módulos',
          icon: Icons.analytics_outlined,
          onExecute: (_) => HarmonicSpectrogramModal.show(context),
        ),
        PromptSuggestion(
          id: 'mod_chords',
          trigger: '@',
          command: '@acordes',
          title: 'Analizador Polifónico de Acordes',
          description: 'Abrir analizador de acordes simultáneos',
          category: 'Módulos',
          icon: Icons.stacked_bar_chart_rounded,
          onExecute: (_) => ChordAnalyzerModal.show(context, viewModel),
        ),
      ];
    }
}
